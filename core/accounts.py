ORDER = ["유동자산", "비유동자산", "유동부채", "비유동부채", "자본",
         "매출", "매출원가", "판매비와관리비", "영업외수익", "영업외비용", "법인세", "미분류"]


def classify_one(name: str) -> tuple[str, str]:
    s = str(name).replace(" ", "")
    for group, sub, keys in RULES:
        for k in keys:
            if k in s:
                return group, sub
    return "미분류", "미분류"


def classify(df: pd.DataFrame, col: str = "계정과목") -> pd.DataFrame:
    out = df.copy()
    pairs = out[col].map(classify_one)
    out["구분"] = [p[0] for p in pairs]
    out["세부구분"] = [p[1] for p in pairs]
    out["세부구분"] = pd.Categorical(out["세부구분"], categories=ORDER, ordered=True)
    return out


def subtotal(df: pd.DataFrame, sub: str, col: str) -> float:
    """세부구분 합계. 없으면 0."""
    m = df[df["세부구분"] == sub]
    return float(m[col].sum()) if len(m) else 0.0


def find(df: pd.DataFrame, keyword: str, col: str) -> float:
    """계정명에 키워드가 든 계정의 합계."""
    m = df[df["계정과목"].astype(str).str.replace(" ", "").str.contains(keyword, na=False)]
    return float(m[col].sum()) if len(m) else 0.0


def josa(word: str, pair: str = "이/가") -> str:
    """받침 유무에 따라 조사를 고른다. pair는 '이/가', '은/는', '을/를'."""
    a, b = pair.split("/")
    w = str(word).rstrip(")]』」』 ").strip()
    if not w:
        return b
    ch = w[-1]
    if "가" <= ch <= "힣":
        return a if (ord(ch) - 0xAC00) % 28 else b
    if ch.isdigit():
        return a if ch in "0136780" else b
    return a
